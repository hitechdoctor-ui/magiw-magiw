export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let text: string = messages[locale][key] ?? messages.el[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${name}\\}`, "g"), String(value));
    }
  }
  return text;
}

export function getCollectionMessages(locale: Locale, key: "editorial" | "atelier") {
  const prefix =
    key === "editorial" ? "collectionEditorial" : "collectionAtelier";
  return {
    navLabel: translate(locale, `${prefix}Nav` as MessageKey),
    title: translate(locale, `${prefix}Title` as MessageKey),
    description: translate(locale, `${prefix}Desc` as MessageKey),
  };
}
